// Measures every sound in content.js and writes levels.js: the playback gain for each one.
//   swiftc -O tools/measure.swift -o /tmp/measure && node tools/levels.mjs /tmp/measure
// Rules:
//   - A folder is matched as a whole ("album gain"), so pieces keep their loudness relative to each other.
//     Studio tracks are matched one by one, since each comes from a different release.
//   - Target -16 LUFS integrated. Turning down is always allowed; turning up only as far as the loudest
//     true peak in the group stays at or under -1 dBTP, so nothing ever needs a limiter.
//   - Gains are rounded to 0.1 dB; 0 means the file plays untouched.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const TARGET = -16, CEILING = -1;
const meter = process.argv[2];
globalThis.window = {};
eval(readFileSync('content.js', 'utf8'));
const S = window.SITE;

const lufs = z => -0.691 + 10 * Math.log10(z);
function gated(blocks) { // BS.1770 gating over any set of 400 ms blocks
  const abs = blocks.filter(z => z > 0 && lufs(z) > -70);
  if (!abs.length) return -Infinity;
  const rel = lufs(abs.reduce((a, b) => a + b, 0) / abs.length) - 10;
  const kept = abs.filter(z => lufs(z) > rel);
  return lufs(kept.reduce((a, b) => a + b, 0) / kept.length);
}

const out = {};
for (const c of S.collections) {
  const m = c.items.map(it => {
    const file = `audio/${c.id}/${it.id}.${it.ext || 'flac'}`;
    const r = JSON.parse(execFileSync(meter, [file], { maxBuffer: 1 << 28 }).toString());
    return { it, ...r };
  });
  const groups = (c.levels || (c.kind === 'studio' ? 'track' : 'album')) === 'track' ? m.map(x => [x]) : [m];
  for (const g of groups) {
    const L = gated(g.flatMap(x => x.blocks)), tp = Math.max(...g.map(x => x.tp));
    let gain = TARGET - L;
    if (gain > 0) gain = Math.max(0, Math.min(gain, CEILING - tp));
    gain = Math.round(gain * 10) / 10 || 0;
    for (const x of g) out[`${c.id}/${x.it.id}`] = { gain, lufs: x.lufs, tp: x.tp };
    console.log(`${c.id}${g.length === 1 && groups.length > 1 ? '/' + g[0].it.id : ''}: ${L.toFixed(1)} LUFS, peak ${tp.toFixed(1)} dBTP -> ${gain > 0 ? '+' : ''}${gain} dB`);
  }
}
writeFileSync('levels.js', `// Generated by tools/levels.mjs: playback gain (dB) per sound, from BS.1770 loudness. Target ${TARGET} LUFS,
// never raised past ${CEILING} dBTP. Don't edit by hand; re-run the tool after adding or changing audio.
window.LEVELS = ${JSON.stringify(out, null, 1)};
`);
